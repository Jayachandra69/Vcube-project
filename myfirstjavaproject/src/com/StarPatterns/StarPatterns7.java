package com.StarPatterns;

public class StarPatterns7 {

	public static void main(String[] args) {
		System.out.println("Main Method Started !!");
		
		for(int i=1;i<=6;i++) {
			for(int j=1;j<=i;j++) {
				System.out.print(j);
			}
			System.out.println();
		}
		
		System.out.println("Main Method Ended !!");
	}

}
